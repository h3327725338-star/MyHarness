import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { expect, it } from "vitest";
import { registerHtmlPreview } from "../src/modes/web/html-preview.ts";
import { WebHttpServer } from "../src/modes/web/http-server.ts";
import { launchChromium } from "../src/tools/web-search/browser/chromium.ts";
import { detectInstalledBrowsers } from "../src/tools/web-search/browser/firefox.ts";

const installed = detectInstalledBrowsers();
const chromium = installed.find((entry) => entry.kind === "chrome") ?? installed.find((entry) => entry.kind === "edge");

/** Tells the test what the page looks like from inside (the frame is cross-origin to the test page). */
const PROBE = `<script>
const node = document.getElementById("p")?.firstChild;
const rectOf = (from, to) => { if (!node) return null; const r = document.createRange(); r.setStart(node, from); r.setEnd(node, to); const b = r.getBoundingClientRect(); return { left: b.left, top: b.top, right: b.right, bottom: b.bottom }; };
parent.postMessage({ type: "probe", compat: document.compatMode, text: document.getElementById("p")?.textContent, ok: window.__ok === 1,
	bridgeFirstInHead: !!document.head.firstElementChild?.textContent.includes("myharness:selection"),
	alpha: rectOf(0, 5), beta: rectOf(6, 10), gamma: rectOf(11, 16) }, "*");
</script>`;
const WORDS = '<p id="p" style="margin:40px 20px">alpha beta gamma delta epsilon zeta</p>';
const BODY_STYLE = 'style="margin:0;font:16px/24px monospace"';

const PAGES: Record<string, string | Buffer> = {
	"select.html": `<!doctype html><html><head><title>select</title></head><body ${BODY_STYLE}>${WORDS}${PROBE}</body></html>`,
	// Windows PowerShell 5.1 writes UTF-16LE with a byte-order mark: the page must still render, with the bridge.
	"utf16.html": Buffer.concat([
		Buffer.from([0xff, 0xfe]),
		Buffer.from(
			`<!doctype html><html><head><title>utf16</title></head><body ${BODY_STYLE}>${WORDS}${PROBE}</body></html>`,
			"utf16le",
		),
	]),
	// A comment before the doctype: the bridge must not go before the doctype (quirks mode).
	"prologue.html": `<!-- generated by a tool --><!doctype html><title>x</title><body ${BODY_STYLE}>${WORDS}${PROBE}</body>`,
	// No <head> tag, but a "<head>" inside a script: the bridge must not land inside that script.
	"script-head.html": `<!doctype html><html><body ${BODY_STYLE}><script>window.__ok = 1; var s = "<head><title>x</title></head>";</script>${WORDS}${PROBE}</body></html>`,
	// An untrusted page that posts the bridge's messages itself, without any input.
	"hostile.html": `<!doctype html><html><head><title>hostile</title></head><body ${BODY_STYLE}>${WORDS}<script>
const forge = (message) => parent.postMessage({ type: "myharness:selection", ...message }, location.origin);
setInterval(() => {
	if (location.hash === "#escape") { forge({ kind: "escape" }); forge({ kind: "press", button: 0 }); }
	else forge({ kind: "select", text: "ATTACKER CHOSEN TEXT", x: -1000, y: 5000 });
}, 100);
</script></body></html>`,
};

const FRAME = { left: 300, top: 120, width: 420, height: 260 };

const INDEX = `<!doctype html><meta charset="utf-8">
<link rel="stylesheet" href="/css/tokens.css"><link rel="stylesheet" href="/css/base.css"><link rel="stylesheet" href="/css/composer.css">
<style>
body { margin: 0; }
#host { position: fixed; left: 20px; top: 20px; margin: 0; font: 16px/24px monospace; }
.stage { position: fixed; left: ${FRAME.left}px; top: ${FRAME.top}px; width: ${FRAME.width}px; height: ${FRAME.height}px; }
.stage iframe { width: 100%; height: 100%; border: 0; background: #fff; }
#send { position: fixed; left: 20px; top: 600px; width: 160px; height: 44px; }
</style>
<p id="host">parent words to translate</p>
<div class="stage"><iframe class="html-frame" sandbox="allow-scripts allow-forms allow-modals allow-popups allow-downloads" referrerpolicy="no-referrer"></iframe></div>
<button id="send">Send</button>
<div id="qh"></div>
<script type="module" src="/test/test.js"></script>`;

const TEST_JS = `
import { h, render } from '/vendor/preact.js';
import { FloatingQuoteToolbar } from '/js/quote-toolbar.js';
window.__probes = [];
window.__sends = 0;
// What the bridge reported and how this window stood then, for the failure messages.
window.__log = [];
addEventListener('message', (e) => {
	const frame = document.querySelector('iframe.html-frame');
	if (e.data && e.data.type === 'myharness:selection')
		window.__log.push([e.data.kind, e.data.text, navigator.userActivation.isActive, document.activeElement === frame].join('|'));
});
addEventListener('message', (e) => { if (e.data && e.data.type === 'probe') window.__probes.push(e.data); });
document.getElementById('send').addEventListener('mousedown', () => { window.__sends += 1; });
render(h(FloatingQuoteToolbar, {}), document.getElementById('qh'));
window.__load = (url) => new Promise((resolve) => {
	const frame = document.querySelector('iframe.html-frame');
	window.__probes = [];
	frame.onload = () => resolve(true);
	frame.src = url;
});
window.__ready = true;
`;

type Rect = { left: number; top: number; right: number; bottom: number };
type Probe = {
	compat: string;
	text: string;
	ok: boolean;
	bridgeFirstInHead: boolean;
	alpha: Rect;
	beta: Rect;
	gamma: Rect;
};

/**
 * The Translate bubble for a selection inside a previewed (sandboxed, cross-origin) HTML page, driven with real input
 * (CDP), since it depends on user activation and focus: a mouse drag, Shift+arrows and Ctrl+A show it inside the frame;
 * a page posting the bridge's messages on its own never shows it outside its frame, nor without the user's input there,
 * and cannot close a card that came from elsewhere. Also checks that the bridge keeps UTF-16 and odd prologues intact.
 */
it.skipIf(process.env.MYHARNESS_TARGETED_BROWSER_E2E !== "1" || !chromium)(
	"the preview frame's Translate bubble needs real input there and stays inside the frame",
	async () => {
		const root = mkdtempSync(join(process.env.MYHARNESS_TEMP_DIR || tmpdir(), "myharness-preview-bridge-"));
		const site = join(root, "site");
		const testDir = join(root, "test");
		mkdirSync(site);
		mkdirSync(testDir);
		for (const [name, content] of Object.entries(PAGES)) writeFileSync(join(site, name), content);
		writeFileSync(join(testDir, "index.html"), INDEX);
		writeFileSync(join(testDir, "test.js"), TEST_JS);

		const server = new WebHttpServer();
		const translated: string[] = [];
		for (const dir of ["js", "vendor", "css"])
			server.mount({ prefix: `/${dir}/`, directory: fileURLToPath(new URL(`../web/${dir}`, import.meta.url)) });
		server.mount({ prefix: "/test/", directory: testDir });
		registerHtmlPreview(server, (input) => join(site, String(input)));
		server.route("GET", "/api/translate", () => ({ preference: "auto", target: "zh-CN" }));
		server.route("POST", "/api/translate", ({ body }) => {
			translated.push(String((body as { text?: unknown }).text ?? ""));
			return { translation: "TRANSLATED", target: "zh-CN", preference: "auto", model: "m" };
		});

		const launch = launchChromium({
			executable: chromium!.executable,
			profileDir: join(root, "chrome"),
			headless: true,
			brand: chromium!.kind === "edge" ? "Microsoft Edge" : "Google Chrome",
		});
		const bridge = launch.bridge as unknown as {
			send(method: string, params?: Record<string, unknown>, sessionId?: string): Promise<Record<string, unknown>>;
			quit?(): Promise<void>;
		};
		const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));
		try {
			await launch.ready({ timeoutMs: 30000, isAlive: () => launch.child.exitCode === null });
			const { port } = await server.listen(0);
			const base = `http://127.0.0.1:${port}`;
			const previewUrl = async (name: string) => {
				const response = await fetch(`${base}/api/files/site`, {
					method: "POST",
					headers: { "content-type": "application/json", "x-myharness-web": "1" },
					body: JSON.stringify({ path: name }),
				});
				return ((await response.json()) as { url: string }).url;
			};

			const created = await bridge.send("Target.createTarget", { url: "about:blank" });
			const attached = await bridge.send("Target.attachToTarget", {
				targetId: String(created.targetId),
				flatten: true,
			});
			const sessionId = String(attached.sessionId);
			const send = (method: string, params: Record<string, unknown> = {}) => bridge.send(method, params, sessionId);
			const evaluate = async <T>(expression: string): Promise<T> => {
				const reply = await send("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true });
				return (reply.result as { value?: T } | undefined)?.value as T;
			};
			const waitFor = async <T>(expression: string, timeoutMs = 3000): Promise<T | null> => {
				const deadline = Date.now() + timeoutMs;
				for (;;) {
					const value = await evaluate<T>(expression);
					if (value) return value;
					if (Date.now() > deadline) return null;
					await sleep(50);
				}
			};
			await send("Emulation.setDeviceMetricsOverride", {
				width: 1000,
				height: 760,
				deviceScaleFactor: 1,
				mobile: false,
			});
			await send("Page.navigate", { url: `${base}/test/index.html` });
			expect(await waitFor("window.__ready === true", 10000), "the test page never came up").toBe(true);

			const mouse = (type: string, x: number, y: number, buttons: number) =>
				send("Input.dispatchMouseEvent", {
					type,
					x,
					y,
					button: type === "mouseMoved" && !buttons ? "none" : "left",
					buttons,
					clickCount: 1,
				});
			const click = async (x: number, y: number) => {
				await mouse("mouseMoved", x, y, 0);
				await mouse("mousePressed", x, y, 1);
				await mouse("mouseReleased", x, y, 0);
			};
			const drag = async (from: { x: number; y: number }, to: { x: number; y: number }) => {
				await mouse("mouseMoved", from.x, from.y, 0);
				await mouse("mousePressed", from.x, from.y, 1);
				for (let step = 1; step <= 8; step++)
					await mouse(
						"mouseMoved",
						from.x + ((to.x - from.x) * step) / 8,
						from.y + ((to.y - from.y) * step) / 8,
						1,
					);
				await mouse("mouseReleased", to.x, to.y, 0);
			};
			const KEYS: Record<string, { code: string; vk: number }> = {
				Shift: { code: "ShiftLeft", vk: 16 },
				Control: { code: "ControlLeft", vk: 17 },
				ArrowRight: { code: "ArrowRight", vk: 39 },
				a: { code: "KeyA", vk: 65 },
			};
			const key = (type: "rawKeyDown" | "keyUp", name: string, modifiers = 0) =>
				send("Input.dispatchKeyEvent", {
					type,
					key: name,
					code: KEYS[name]!.code,
					windowsVirtualKeyCode: KEYS[name]!.vk,
					nativeVirtualKeyCode: KEYS[name]!.vk,
					modifiers,
				});
			const press = async (name: string, modifiers = 0) => {
				await key("rawKeyDown", name, modifiers);
				await key("keyUp", name, modifiers);
			};
			const bubble = () =>
				evaluate<Rect | null>(
					"(() => { const b = document.querySelector('.floating-quote-bar'); if (!b) return null; const r = b.getBoundingClientRect(); return { left: r.left, top: r.top, right: r.right, bottom: r.bottom }; })()",
				);
			const waitBubble = (timeoutMs = 2000) =>
				waitFor<Rect>(
					"(() => { const b = document.querySelector('.floating-quote-bar'); if (!b) return null; const r = b.getBoundingClientRect(); return { left: r.left, top: r.top, right: r.right, bottom: r.bottom }; })()",
					timeoutMs,
				);
			const cardOpen = () => evaluate<boolean>("!!document.querySelector('.translate-card:not(.leaving)')");
			const insideFrame = (rect: Rect) =>
				rect.left >= FRAME.left &&
				rect.top >= FRAME.top &&
				rect.right <= FRAME.left + FRAME.width &&
				rect.bottom <= FRAME.top + FRAME.height;
			const load = async (name: string) => {
				await evaluate(`window.__load(${JSON.stringify(await previewUrl(name))})`);
				return (await waitFor<Probe>("window.__probes[0]", 5000)) as Probe;
			};
			const at = (probe: Probe, word: "alpha" | "beta" | "gamma", side: "left" | "right") => ({
				x: FRAME.left + probe[word][side] + (side === "left" ? 1 : -1),
				y: FRAME.top + (probe[word].top + probe[word].bottom) / 2,
			});
			const translateBubble = async () => {
				const rect = await waitBubble();
				if (!rect)
					throw new Error(
						`no bubble; the bridge reported: ${await evaluate("window.__log.slice(-12).join(', ')")}`,
					);
				await click(rect.left + 20, (rect.top + rect.bottom) / 2);
				expect(
					await waitFor("!!document.querySelector('.translate-card .tr-target, .translate-card .tr-main')"),
					"no translation card",
				).toBe(true);
				return translated.at(-1);
			};
			// The card takes the focus when it opens; a click back into the page (blank part) closes it and gives the frame
			// the focus again, as a user does.
			const closeCardInFrame = async () => {
				await click(FRAME.left + 380, FRAME.top + 230);
				expect(
					await waitFor("!document.querySelector('.translate-card')"),
					"a click into the page left its card open",
				).toBe(true);
			};

			// 1) A page posting "select" on a timer, with no input at all: no bubble.
			await evaluate(`window.__load(${JSON.stringify(`${await previewUrl("hostile.html")}#select`)})`);
			await sleep(1200);
			expect(await bubble(), "a page with no user input showed the bubble").toBeNull();
			// Input elsewhere in the app activates this window, but the frame does not have the focus: still none.
			await click(150, 470);
			await sleep(800);
			expect(await bubble(), "input outside the frame let the page show the bubble").toBeNull();
			// After a real click in the frame the page may show it, but only inside its own box, never over the app.
			await click(FRAME.left + 200, FRAME.top + 200);
			const forced = await waitBubble();
			expect(forced, "the bubble should follow a real click in the frame").not.toBeNull();
			expect(insideFrame(forced!), `bubble ${JSON.stringify(forced)} left the frame box`).toBe(true);
			expect(
				await evaluate("!!document.elementFromPoint(100, 622)?.closest('#send')"),
				"the Send button is covered",
			).toBe(true);

			// 2) A card opened from the app's own text: the page's forged Esc/press messages do not close it, a click into
			// the frame does (the window loses the focus to it).
			await evaluate(`window.__load(${JSON.stringify(`${await previewUrl("hostile.html")}#escape`)})`);
			const host = await evaluate<Rect>(
				"(() => { const r = document.createRange(); const t = document.getElementById('host').firstChild; r.setStart(t, 0); r.setEnd(t, 12); const b = r.getBoundingClientRect(); return { left: b.left, top: b.top, right: b.right, bottom: b.bottom }; })()",
			);
			await drag(
				{ x: host.left + 1, y: (host.top + host.bottom) / 2 },
				{ x: host.right - 1, y: (host.top + host.bottom) / 2 },
			);
			expect(await translateBubble()).toBe("parent words");
			await sleep(700);
			expect(await cardOpen(), "the page's forged messages closed a card it did not open").toBe(true);
			await click(FRAME.left + 200, FRAME.top + 200);
			expect(
				await waitFor("!document.querySelector('.translate-card')"),
				"a click into the frame left the card open",
			).toBe(true);

			// 3) A real mouse drag in the page: the bubble sits inside the frame, Translate sends the words.
			const page = await load("select.html");
			expect(page.bridgeFirstInHead).toBe(true);
			await drag(at(page, "beta", "left"), at(page, "gamma", "right"));
			const dragged = await waitBubble();
			expect(dragged, "a mouse selection in the frame showed no bubble").not.toBeNull();
			expect(insideFrame(dragged!)).toBe(true);
			expect(await translateBubble()).toBe("beta gamma");
			await closeCardInFrame();

			// A drag that outlasts the user activation its press gave (about 5 s; moving the mouse does not renew it).
			const from = at(page, "alpha", "left");
			const to = at(page, "gamma", "right");
			await mouse("mouseMoved", from.x, from.y, 0);
			await mouse("mousePressed", from.x, from.y, 1);
			for (let step = 1; step <= 12; step++) {
				await mouse("mouseMoved", from.x + ((to.x - from.x) * step) / 12, from.y, 1);
				await sleep(500);
			}
			await mouse("mouseReleased", to.x, to.y, 0);
			expect(await translateBubble(), "a slow drag (over 5 s)").toBe("alpha beta gamma");
			await closeCardInFrame();

			// 4) Keyboard: a word picked by double-click, grown with Shift+ArrowRight; then Ctrl+A.
			const word = at(page, "beta", "left");
			await mouse("mouseMoved", word.x + 4, word.y, 0);
			await send("Input.dispatchMouseEvent", {
				type: "mousePressed",
				x: word.x + 4,
				y: word.y,
				button: "left",
				buttons: 1,
				clickCount: 1,
			});
			await send("Input.dispatchMouseEvent", {
				type: "mouseReleased",
				x: word.x + 4,
				y: word.y,
				button: "left",
				buttons: 0,
				clickCount: 1,
			});
			await send("Input.dispatchMouseEvent", {
				type: "mousePressed",
				x: word.x + 4,
				y: word.y,
				button: "left",
				buttons: 1,
				clickCount: 2,
			});
			await send("Input.dispatchMouseEvent", {
				type: "mouseReleased",
				x: word.x + 4,
				y: word.y,
				button: "left",
				buttons: 0,
				clickCount: 2,
			});
			// The double-click's own bubble ("beta") comes first; the keys replace it.
			await waitBubble();
			await key("rawKeyDown", "Shift", 8);
			for (let i = 0; i < 6; i++) await press("ArrowRight", 8);
			await key("keyUp", "Shift", 0);
			// Each key reports the selection so far; let the last report arrive.
			await sleep(200);
			expect(
				await translateBubble(),
				`Shift+arrows in the frame: ${await evaluate("window.__log.slice(-12).join(', ')")}`,
			).toBe("beta gamma");
			await closeCardInFrame();
			await key("rawKeyDown", "Control", 2);
			await press("a", 2);
			await key("keyUp", "Control", 0);
			await sleep(200);
			expect(await translateBubble(), "Ctrl+A in the frame").toContain("alpha beta gamma delta epsilon zeta");
			await closeCardInFrame();

			// 5) A UTF-16LE page with its byte-order mark renders (in standards mode) and the bridge works in it.
			const utf16 = await load("utf16.html");
			expect(utf16.text).toBe("alpha beta gamma delta epsilon zeta");
			expect(utf16.compat).toBe("CSS1Compat");
			expect(utf16.bridgeFirstInHead).toBe(true);
			await drag(at(utf16, "alpha", "left"), at(utf16, "beta", "right"));
			expect(await translateBubble(), "a selection in a UTF-16 page").toBe("alpha beta");

			// 6) Odd prologues: still standards mode after a leading comment, the page's own script intact.
			const prologue = await load("prologue.html");
			expect(prologue.compat).toBe("CSS1Compat");
			expect(prologue.bridgeFirstInHead).toBe(true);
			const scriptHead = await load("script-head.html");
			expect(scriptHead.ok, "the page's own script broke").toBe(true);
			expect(scriptHead.bridgeFirstInHead).toBe(true);
			expect(scriptHead.text).toBe("alpha beta gamma delta epsilon zeta");
		} finally {
			await bridge.quit?.().catch(() => {});
			if (launch.child.pid) {
				try {
					launch.child.kill("SIGKILL");
				} catch {
					/* already gone */
				}
			}
			await server.close();
			rmSync(root, { recursive: true, force: true, maxRetries: 20, retryDelay: 250 });
		}
	},
	90000,
);
